import 'package:supabase_flutter/supabase_flutter.dart';
import 'package:crafts/features/audit/audit_log_model.dart';

/// Repository for audit log operations
/// Handles writing audit entries and reading/filtering audit logs
class AuditLogRepository {
  final SupabaseClient _supabase = Supabase.instance.client;
  final String _tenantId;

  AuditLogRepository({String? tenantId}) : _tenantId = tenantId ?? 'default_tenant';

  /// Write an audit log entry
  /// This is append-only - no UPDATE or DELETE permitted by RLS policies
  Future<AuditLogEntry> logAction({
    required String action,
    String? entityType,
    String? entityId,
    Map<String, dynamic>? details,
  }) async {
    final user = _supabase.auth.currentUser;
    final userId = user?.id;

    final entry = AuditLogEntry(
      id: '', // Will be generated by database
      tenantId: _tenantId,
      userId: userId,
      action: action,
      entityType: entityType,
      entityId: entityId,
      details: details,
      createdAt: DateTime.now(),
    );

    // Insert into audit_logs - RLS will enforce tenant_id isolation
    final response = await _supabase.from('audit_logs').insert({
      'tenant_id': _tenantId,
      'user_id': userId,
      'action': action,
      'entity_type': entityType,
      'entity_id': entityId,
      'details': details,
    }).select();

    if (response.isNotEmpty) {
      final created = response.first;
      return AuditLogEntry.fromMap(created);
    }

    throw Exception('Failed to write audit log entry');
  }

  /// Fetch audit logs with optional filtering
  Future<List<AuditLogEntry>> fetchLogs({
    String? actionFilter,
    String? entityTypeFilter,
    DateTime? startDate,
    DateTime? endDate,
    int limit = 100,
  }) async {
    // Build filter map for Supabase
    final Map<String, dynamic> filters = {};
    if (actionFilter != null && actionFilter.isNotEmpty) {
      filters['action'] = actionFilter;
    }
    if (entityTypeFilter != null && entityTypeFilter.isNotEmpty) {
      filters['entity_type'] = entityTypeFilter;
    }

    // Build date range filter
    final Map<String, dynamic> selectOptions = {
      'tenant_id': _tenantId,
      'order': {'column': 'created_at', 'ascending': false},
      'limit': limit,
    };
    if (startDate != null) {
      selectOptions['gte'] = {'created_at': startDate.toIso8601String()};
    }
    if (endDate != null) {
      selectOptions['lte'] = {'created_at': endDate.toIso8601String()};
    }

    final response = await _supabase
        .from('audit_logs')
        .select()
        .eq('tenant_id', _tenantId)
        .order('created_at', ascending: false)
        .limit(limit);

    // Apply additional filters via .filter() if needed
    if (actionFilter != null && actionFilter.isNotEmpty) {
      response.eq('action', actionFilter);
    }
    if (entityTypeFilter != null && entityTypeFilter.isNotEmpty) {
      response.eq('entity_type', entityTypeFilter);
    }

    return (response as List).map((map) => AuditLogEntry.fromMap(map)).toList();
  }

  /// Log user login event
  Future<AuditLogEntry> logUserLogin({required String loginMethod}) async {
    return logAction(
      action: 'user_login',
      details: {'login_method': loginMethod},
    );
  }

  /// Log user logout event
  Future<AuditLogEntry> logUserLogout() async {
    return logAction(
      action: 'user_logout',
    );
  }

  /// Log debt modification
  Future<AuditLogEntry> logDebtModification({
    required String debtId,
    required String action, // e.g., 'modify', 'status_change'
    Map<String, dynamic>? changes,
  }) async {
    return logAction(
      action: action,
      entityType: 'debt',
      entityId: debtId,
      details: changes,
    );
  }

  /// Log payment recording
  Future<AuditLogEntry> logPaymentRecording({
    required String paymentId,
    required double amount,
    required String paymentMethod,
  }) async {
    return logAction(
      action: 'payment_recorded',
      entityType: 'payment',
      entityId: paymentId,
      details: {
        'amount': amount,
        'payment_method': paymentMethod,
      },
    );
  }

  /// Log payment adjustment/compensating transaction
  Future<AuditLogEntry> logPaymentAdjustment({
    required String paymentId,
    required String adjustmentType, // e.g., 'dispute', 'refund', 'correction'
    Map<String, dynamic>? details,
  }) async {
    return logAction(
      action: 'payment_adjustment',
      entityType: 'payment',
      entityId: paymentId,
      details: {'adjustment_type': adjustmentType, ...?details},
    );
  }

  /// Log staff account deactivation/activation
  Future<AuditLogEntry> logStaffRoleChange({
    required String staffId,
    required String action, // e.g., 'deactivate', 'activate'
    Map<String, dynamic>? changes,
  }) async {
    return logAction(
      action: action,
      entityType: 'staff',
      entityId: staffId,
      details: changes,
    );
  }
}